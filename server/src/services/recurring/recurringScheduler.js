import cron from 'node-cron';
import { RecurringRule } from '../../models/RecurringRule.js';
import { Transaction } from '../../models/Transaction.js';
import { Account } from '../../models/Account.js';
import { Notification } from '../../models/Notification.js';
import {
  TRANSACTION_TYPES,
  TRANSACTION_SOURCES,
  RECURRENCE_FREQUENCIES,
} from '../../config/constants.js';
import { evaluateBudgetsForUser } from '../budget/budgetEvaluator.js';
import { logger } from '../../utils/logger.js';

/**
 * Calculates next recurrence occurrence with edge-of-month clamping (DEC-005)
 * Handles Jan 31 -> Feb 28/29, leap years, etc.
 * @param {Date|string} baseDate
 * @param {string} frequency
 * @returns {Date}
 */
export function calculateNextOccurrence(baseDate, frequency) {
  const d = new Date(baseDate);

  if (frequency === RECURRENCE_FREQUENCIES.DAILY) {
    d.setDate(d.getDate() + 1);
    return d;
  }

  if (frequency === RECURRENCE_FREQUENCIES.WEEKLY) {
    d.setDate(d.getDate() + 7);
    return d;
  }

  if (frequency === RECURRENCE_FREQUENCIES.MONTHLY) {
    const desiredDay = d.getDate();
    const targetMonth = d.getMonth() + 1;
    const targetYear = d.getFullYear() + Math.floor(targetMonth / 12);
    const normalizedMonth = targetMonth % 12;

    // Determine max days in target month (e.g. 28, 29, 30, 31)
    const maxDays = new Date(targetYear, normalizedMonth + 1, 0).getDate();
    const clampedDay = Math.min(desiredDay, maxDays);

    return new Date(
      targetYear,
      normalizedMonth,
      clampedDay,
      d.getHours(),
      d.getMinutes(),
      d.getSeconds(),
      d.getMilliseconds()
    );
  }

  if (frequency === RECURRENCE_FREQUENCIES.YEARLY) {
    const desiredDay = d.getDate();
    const targetYear = d.getFullYear() + 1;
    const targetMonth = d.getMonth();

    const maxDays = new Date(targetYear, targetMonth + 1, 0).getDate();
    const clampedDay = Math.min(desiredDay, maxDays);

    return new Date(
      targetYear,
      targetMonth,
      clampedDay,
      d.getHours(),
      d.getMinutes(),
      d.getSeconds(),
      d.getMilliseconds()
    );
  }

  return d;
}

/**
 * Sweeps and executes all eligible recurring rules as of `referenceDate`
 * Ensures complete idempotency against duplicate run dates (DEC-005)
 * @param {Date} [referenceDate=new Date()]
 * @returns {Promise<Object>} Execution summary metrics
 */
export async function processRecurringTransactions(referenceDate = new Date()) {
  const now = new Date(referenceDate);

  // Find all active rules whose nextRunAt has elapsed
  const activeRules = await RecurringRule.find({
    isActive: true,
    nextRunAt: { $lte: now },
    $or: [{ endDate: null }, { endDate: { $gte: now } }],
  });

  let processedCount = 0;
  let generatedCount = 0;
  let skippedCount = 0;

  for (const rule of activeRules) {
    processedCount++;

    const scheduledDate = new Date(rule.nextRunAt);
    const startOfScheduledDay = new Date(
      scheduledDate.getFullYear(),
      scheduledDate.getMonth(),
      scheduledDate.getDate(),
      0,
      0,
      0,
      0
    );
    const endOfScheduledDay = new Date(
      scheduledDate.getFullYear(),
      scheduledDate.getMonth(),
      scheduledDate.getDate(),
      23,
      59,
      59,
      999
    );

    // Idempotency Check: Verify if transaction was already generated for this rule on this day
    const alreadyGenerated = await Transaction.findOne({
      recurrenceRuleId: rule._id,
      transactionDate: {
        $gte: startOfScheduledDay,
        $lte: endOfScheduledDay,
      },
    });

    if (alreadyGenerated) {
      skippedCount++;
    } else {
      // 1. Create Transaction Document
      if (rule.type === TRANSACTION_TYPES.INCOME || rule.type === TRANSACTION_TYPES.EXPENSE) {
        await Transaction.create({
          userId: rule.userId,
          type: rule.type,
          amountMinor: rule.amountMinor,
          currency: rule.currency || 'INR',
          accountId: rule.accountId,
          categoryId: rule.categoryId || null,
          transactionDate: scheduledDate,
          description: rule.title || rule.description,
          notes: rule.notes || 'Auto-generated by SmartSpend Recurring Scheduler',
          paymentMethod: rule.paymentMethod || 'upi',
          source: TRANSACTION_SOURCES.RECURRING,
          recurrenceRuleId: rule._id,
        });

        // 2. Mutate account balance atomically
        const delta =
          rule.type === TRANSACTION_TYPES.INCOME ? rule.amountMinor : -rule.amountMinor;
        await Account.updateOne(
          { _id: rule.accountId },
          { $inc: { currentBalanceMinor: delta } }
        );

        // 3. Trigger budget evaluation if expense
        if (rule.type === TRANSACTION_TYPES.EXPENSE) {
          await evaluateBudgetsForUser(rule.userId, scheduledDate).catch(() => {});
        }
      } else if (rule.type === TRANSACTION_TYPES.TRANSFER) {
        await Transaction.create({
          userId: rule.userId,
          type: TRANSACTION_TYPES.TRANSFER,
          amountMinor: rule.amountMinor,
          currency: rule.currency || 'INR',
          fromAccountId: rule.fromAccountId,
          toAccountId: rule.toAccountId,
          transactionDate: scheduledDate,
          description: rule.title || 'Recurring Account Transfer',
          notes: rule.notes || 'Auto-generated by SmartSpend Recurring Scheduler',
          paymentMethod: rule.paymentMethod || 'other',
          source: TRANSACTION_SOURCES.RECURRING,
          recurrenceRuleId: rule._id,
        });

        // Mutate both accounts symmetrically (DEC-003)
        await Promise.all([
          Account.updateOne(
            { _id: rule.fromAccountId },
            { $inc: { currentBalanceMinor: -rule.amountMinor } }
          ),
          Account.updateOne(
            { _id: rule.toAccountId },
            { $inc: { currentBalanceMinor: rule.amountMinor } }
          ),
        ]);
      }

      // 4. Create in-app confirmation notification
      const formattedAmount = (rule.amountMinor / 100).toLocaleString('en-IN', {
        minimumFractionDigits: 2,
      });

      await Notification.create({
        userId: rule.userId,
        title: `Recurring Transaction Recorded: ${rule.title}`,
        message: `An automated ${rule.type} of ₹${formattedAmount} was successfully executed and added to your ledger.`,
        type: 'recurring_reminder',
        severity: 'info',
        relatedId: rule._id,
      });

      generatedCount++;
    }

    // 5. Advance nextRunAt
    const nextDate = calculateNextOccurrence(rule.nextRunAt, rule.frequency);

    // If endDate is reached, deactivate rule
    if (rule.endDate && nextDate > new Date(rule.endDate)) {
      rule.isActive = false;
    }

    rule.lastRunAt = rule.nextRunAt;
    rule.nextRunAt = nextDate;
    rule.totalGeneratedCount += 1;
    await rule.save();
  }

  return {
    processedCount,
    generatedCount,
    skippedCount,
    timestamp: now.toISOString(),
  };
}

let cronJobInstance = null;

/**
 * Initializes the node-cron recurring transaction daemon (DEC-005)
 * Runs daily at midnight 00:01:00 UTC (or local)
 */
export function initRecurringCron() {
  if (cronJobInstance) {
    return cronJobInstance;
  }

  // Schedule to run every day at 00:01 AM
  cronJobInstance = cron.schedule('1 0 * * *', async () => {
    try {
      logger.info('Executing scheduled recurring transactions daemon sweep (DEC-005)...');
      const result = await processRecurringTransactions();
      logger.info(
        `Recurring daemon sweep complete: ${result.generatedCount} generated, ${result.skippedCount} skipped.`
      );
    } catch (err) {
      logger.error('Error during scheduled recurring transactions sweep:', err);
    }
  });

  logger.info('Recurring transactions node-cron daemon initialized successfully (00:01 AM daily).');
  return cronJobInstance;
}
